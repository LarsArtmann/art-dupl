// OutputHTML generates HTML output with sorting.
func (p *htmlprinter) OutputHTML(threshold int, sortBy config.SortCriteria) error {
	var allClones []domain.ProcessedClone

	p.dupMutex.Lock()
	for i := range len(p.dupls) {
		allClones = append(allClones, p.dupls[i]...)
	}
	p.dupMutex.Unlock()

	SortProcessedClonesByCriteria(allClones, sortBy)

	p.iota = 0

	for _, cl := range allClones {
		err := p.PrintClones(
			domain.ProcessedCloneGroup{Clones: []domain.ProcessedClone{cl}},
			sortBy,
		)
		if err != nil {
			return fmt.Errorf(
				"output HTML (threshold: %d, sortBy: %s): %w",
				threshold,
				sortBy.String(),
				err,
			)
		}
	}

	return nil
}

// priorityHigher returns true if p1 is higher priority than p2.
func priorityHigher(p1, p2 ClonePriority) bool {
	priorityOrder := map[ClonePriority]int{
		domain.PriorityCritical: 4,
		domain.PriorityHigh:     3,
		domain.PriorityMedium:   2,
		domain.PriorityLow:      1,
	}

	return priorityOrder[p1] > priorityOrder[p2]
}

func suggestionHTML(suggestion string) string {
	if suggestion == "" {
		return ""
	}

	return fmt.Sprintf(`<div class="suggestion">💡 %s</div>`, strings.NewReplacer(
		"&", "&amp;",
		"<", "&lt;",
		">", "&gt;",
		`"`, "&#34;",
		"'", "&#39;",
	).Replace(suggestion))
}

// writeCloneOccurrences renders clone occurrences (non-diff mode) using templ.
func (p *htmlprinter) writeCloneOccurrences(clones []domain.ProcessedClone) error {
	for i, cl := range clones {
		occData := toCloneOccurrenceData(cl)

		err := cloneOccurrence(
			occData,
			p.iota,
			i,
		).Render(context.Background(), p.w)
		if err != nil {
			return err
		}
	}

	return nil
}

func (p *htmlprinter) writeCloneGroupFooter() error {
	_, err := fmt.Fprint(p.w, "</div></div>\n")

	return err
}

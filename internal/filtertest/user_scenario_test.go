// assertFilterResult checks that a file is kept or not kept by the filter.
func assertFilterResult(
	t *testing.T,
	f *gogenfilter.Filter,
	fsPath, description string,
	wantKept bool,
) {
	t.Helper()

	wasKept, err := f.Filter(fsPath)
	if err != nil {
		return
	}

	if wasKept != wantKept {
		if wantKept {
			t.Errorf("%s should be kept (%s)", filepath.Base(fsPath), description)
		} else {
			t.Errorf("%s should NOT be kept (%s)", filepath.Base(fsPath), description)
		}
	}
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()

	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("failed to write %s: %v", filepath.Base(path), err)
	}
}

func createDir(t *testing.T, path string) {
	t.Helper()

	if err := os.MkdirAll(path, 0o755); err != nil {
		t.Fatalf("failed to create dir: %v", err)
	}
}

// TestUserScenario_RealSQLCProject tests the exact scenario from the user's issue:
// - sqlc.yaml in project root
// - SQLC generates files like articles.sql.go, users.sql.go
// - Running art-dupl should filter these SQLC files automatically.
func TestUserScenario_RealSQLCProject(t *testing.T) {
	// Create temporary directory structure
	tmpDir := t.TempDir()

	// Create sqlc.yaml in project root (matching user's structure)
	sqlcConfig := `version: "2"
sql:
  - engine: "postgresql"
    queries: "queries/articles.sql"
    gen:
      go:
        package: "queries"
        out: "internal/storage/queries"
  - engine: "postgresql" 
    queries: "queries/users.sql"
    gen:
      go:
        package: "queries"
        out: "internal/storage/queries"
`
	configPath := filepath.Join(tmpDir, "sqlc.yaml")
	writeFile(t, configPath, sqlcConfig)

	// Create directory structure
	queriesDir := filepath.Join(tmpDir, "internal/storage/queries")
	createDir(t, queriesDir)

	repoDir := filepath.Join(tmpDir, "internal/storage/repository")
	createDir(t, repoDir)

	// Create SQLC generated files (these should be wasKept)
	articlesSQLC := `// Code generated by sqlc. DO NOT EDIT.
// versions:
//   sqlc v1.25.0

package queries

import (
    "context"
    "database/sql"
)

type Article struct {
    ID          int64
    Title       string
    Content     string
    CategoryID  int64
    CreatedAt   sql.NullTime
    UpdatedAt   sql.NullTime
}

type Category struct {
    ID          int64
    Name        string
    Description string
}

func (q *Queries) GetArticle(ctx context.Context, id int64) (Article, error) {
    return Article{}, nil
}

func (q *Queries) ListArticles(ctx context.Context) ([]Article, error) {
    return nil, nil
}
`
	writeFile(t, filepath.Join(queriesDir, "articles.sql.go"), articlesSQLC)

	usersSQLC := `// Code generated by sqlc. DO NOT EDIT.
// versions:
//   sqlc v1.25.0

package queries

import (
    "context"
    "database/sql"
)

type User struct {
    ID        int64
    Email     string
    Password  string
    CreatedAt sql.NullTime
    UpdatedAt sql.NullTime
}

func (q *Queries) GetUser(ctx context.Context, id int64) (User, error) {
    return User{}, nil
}

func (q *Queries) GetUserByEmail(ctx context.Context, email string) (User, error) {
    return User{}, nil
}
`
	writeFile(t, filepath.Join(queriesDir, "users.sql.go"), usersSQLC)

	// Create regular Go files with duplicate code (these should be detected)
	articleRepo := `package repository

type ArticleModel struct {
    ID          int64
    Title       string
    Content     string
    CategoryID  int64
}

type CategoryModel struct {
    ID          int64
    Name        string
    Description string
}

func (r *Repository) SaveArticle(article ArticleModel) error {
    return nil
}
`
	writeFile(t, filepath.Join(repoDir, "article_repository.go"), articleRepo)

	mockRepo := `package repository

type ArticleModel struct {
    ID          int64
    Title       string
    Content     string
    CategoryID  int64
}

type CategoryModel struct {
    ID          int64
    Name        string
    Description string
}

func (m *MockRepository) SaveArticle(article ArticleModel) error {
    return nil
}
`
	writeFile(t, filepath.Join(repoDir, "mock_repository.go"), mockRepo)

	// Test FindSQLCConfigs finds the config
	configs, err := gogenfilter.FindSQLCConfigs([]string{tmpDir})
	if err != nil {
		t.Fatalf("FindSQLCConfigs failed: %v", err)
	}

	if len(configs) == 0 {
		t.Error("Should find sqlc.yaml in project root")
	}

	// Test GetSQLOutputDirs extracts correct output directories
	outputDirs, err := gogenfilter.GetSQLOutputDirs([]string{tmpDir})
	if err != nil {
		t.Fatalf("GetSQLOutputDirs failed: %v", err)
	}

	if len(outputDirs) == 0 {
		t.Error("Should extract output directories from sqlc.yaml")
	}

	expectedOutputDir := filepath.Join(tmpDir, "internal/storage/queries")
	found := slices.Contains(outputDirs, expectedOutputDir)

	if !found {
		t.Errorf("Should have the queries output directory: %s", expectedOutputDir)
	}

	// Test that filter correctly identifies SQLC files
	filterConfig, filterErr := gogenfilter.WithFilterOptions(gogenfilter.FilterSQLC)
	if filterErr != nil {
		t.Fatalf("WithFilterOptions() error: %v", filterErr)
	}

	f, filterErr := gogenfilter.NewFilter(
		filterConfig,
		gogenfilter.WithFS(os.DirFS("/")),
	)
	if filterErr != nil {
		t.Fatalf("NewFilter() error: %v", filterErr)
	}

	// Verify filter results
	type filterCheck struct {
		path     string
		desc     string
		wantKeep bool
	}
	for _, fc := range []filterCheck{
		{filepath.Join(queriesDir, "articles.sql.go"), "SQLC generated", true},
		{filepath.Join(queriesDir, "users.sql.go"), "SQLC generated", true},
		{filepath.Join(repoDir, "article_repository.go"), "regular Go file", false},
		{filepath.Join(repoDir, "mock_repository.go"), "regular Go file", false},
	} {
		assertFilterResult(t, f, toFSPath(fc.path), fc.desc, fc.wantKeep)
	}
}

// TestSQLCOutputDirectoryFiltering tests that files in SQLC output directories are wasKept.
func TestSQLCOutputDirectoryFiltering(t *testing.T) {
	tmpDir := t.TempDir()

	// Create sqlc.yaml with nested output directory (matching user's structure)
	sqlcConfig := `version: "2"
sql:
  - engine: "postgresql"
    queries: "queries/users.sql"
    gen:
      go:
        package: "queries"
        out: "db/sqlc"
`

	configPath := filepath.Join(tmpDir, "sqlc.yaml")
	writeFile(t, configPath, sqlcConfig)

	// Create nested directory structure
	queriesDir := filepath.Join(tmpDir, "db/sqlc")
	createDir(t, queriesDir)

	// Create SQLC file in nested directory
	sqlcFile := `// Code generated by sqlc. DO NOT EDIT.
package queries

type User struct {
    ID   int64
    Name string
}
`

	sqlcFilePath := filepath.Join(queriesDir, "users.sql.go")
	writeFile(t, sqlcFilePath, sqlcFile)

	// Test GetSQLOutputDirs finds the nested directory
	outputDirs, err := gogenfilter.GetSQLOutputDirs([]string{tmpDir})
	if err != nil {
		t.Fatalf("GetSQLOutputDirs failed: %v", err)
	}

	expectedOutputDir := filepath.Join(tmpDir, "db/sqlc")
	if !slices.Contains(outputDirs, expectedOutputDir) {
		t.Errorf("Should find nested SQLC output directory: %s", expectedOutputDir)
	}

	// Test filter recognizes SQLC files by both name and content
	filterConfig, filterErr := gogenfilter.WithFilterOptions(gogenfilter.FilterSQLC)
	if filterErr != nil {
		t.Fatalf("WithFilterOptions() error: %v", filterErr)
	}

	fltr, filterErr := gogenfilter.NewFilter(
		filterConfig,
		gogenfilter.WithFS(os.DirFS("/")),
	)
	if filterErr != nil {
		t.Fatalf("NewFilter() error: %v", filterErr)
	}

	if wasKept, filterErr := fltr.Filter(toFSPath(sqlcFilePath)); filterErr == nil && !wasKept {
		t.Error("users.sql.go in SQLC output directory should be wasKept")
	}
}

// TestParentDirectorySQLCDetection tests finding sqlc.yaml in parent directories.
func TestParentDirectorySQLCDetection(t *testing.T) {
	tmpDir := t.TempDir()

	// Create sqlc.yaml in "project root"
	projectRoot := tmpDir
	sqlcConfig := `version: "2"
sql:
  - engine: "postgresql"
    queries: "queries/users.sql"
    gen:
      go:
        package: "queries"
        out: "internal/db"
`

	configPath := filepath.Join(projectRoot, "sqlc.yaml")
	writeFile(t, configPath, sqlcConfig)

	// Create subdirectory structure (simulating running art-dupl on a subdirectory)
	subDir := filepath.Join(projectRoot, "internal/db")
	if err := os.MkdirAll(subDir, 0o755); err != nil {
		t.Fatalf("failed to create subdir: %v", err)
	}

	// Create SQLC file in subdirectory
	sqlcFile := `// Code generated by sqlc. DO NOT EDIT.
package queries

type User struct {
    ID   int64
    Name string
}
`

	sqlcFilePath := filepath.Join(subDir, "users.sql.go")
	writeFile(t, sqlcFilePath, sqlcFile)

	// Test that FindSQLCConfigs finds sqlc.yaml even when analyzing subdirectory
	configs, err := gogenfilter.FindSQLCConfigs([]string{subDir})
	if err != nil {
		t.Fatalf("FindSQLCConfigs failed: %v", err)
	}

	if len(configs) == 0 {
		t.Error("Should find sqlc.yaml in parent directory")
	}

	// Test that output directory is correct (relative to project root)
	outputDirs, err := gogenfilter.GetSQLOutputDirs([]string{subDir})
	if err != nil {
		t.Fatalf("GetSQLOutputDirs failed: %v", err)
	}

	expectedOutputDir := filepath.Join(projectRoot, "internal/db")
	found := slices.Contains(outputDirs, expectedOutputDir)

	if !found {
		t.Errorf("Should resolve output directory relative to project root: %s", expectedOutputDir)
	}
}

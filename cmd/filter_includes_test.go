func TestGeneratorIncludesAny(t *testing.T) {
	tests := []struct {
		name     string
		includes generatorIncludes
		expected bool
	}{
		{"empty", generatorIncludes{}, false},
		{"sqlc only", generatorIncludes{SQLC: true}, true},
		{"templ only", generatorIncludes{Templ: true}, true},
		{"protobuf only", generatorIncludes{Protobuf: true}, true},
		{"mockgen only", generatorIncludes{Mockgen: true}, true},
		{"stringer only", generatorIncludes{Stringer: true}, true},
		{"all set", generatorIncludes{
			SQLC: true, Templ: true, Protobuf: true, Mockgen: true, Stringer: true,
		}, true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := tt.includes.any(); got != tt.expected {
				t.Errorf("any() = %v, want %v", got, tt.expected)
			}
		})
	}
}

func TestGeneratorIncludesAllowsContent(t *testing.T) {
	sqlcContent := []byte("// Code generated by sqlc. DO NOT EDIT.\npackage db\nfunc Q() {}\n")
	templContent := []byte("// Code generated by templ. DO NOT EDIT.\npackage x\nvar _ = templ.Component\n")
	protobufContent := []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb\n")
	mockgenContent := []byte("// Code generated by MockGen. DO NOT EDIT.\npackage mocks\n")
	stringerContent := []byte(`// Code generated by "stringer". DO NOT EDIT.
package x
`)
	regularContent := []byte("package main\nfunc main() {}\n")

	tests := []struct {
		name     string
		includes generatorIncludes
		content  []byte
		expected bool
	}{
		{"sqlc flag + sqlc content", generatorIncludes{SQLC: true}, sqlcContent, true},
		{"templ flag + templ content", generatorIncludes{Templ: true}, templContent, true},
		{"protobuf flag + protobuf content", generatorIncludes{Protobuf: true}, protobufContent, true},
		{"mockgen flag + mockgen content", generatorIncludes{Mockgen: true}, mockgenContent, true},
		{"stringer flag + stringer content", generatorIncludes{Stringer: true}, stringerContent, true},
		{"sqlc flag + regular content", generatorIncludes{SQLC: true}, regularContent, false},
		{"no flags + sqlc content", generatorIncludes{}, sqlcContent, false},
		{"sqlc flag + templ content (wrong category)", generatorIncludes{SQLC: true}, templContent, false},
		{"templ flag + sqlc content (wrong category)", generatorIncludes{Templ: true}, sqlcContent, false},
		{"empty content", generatorIncludes{SQLC: true}, []byte{}, false},
		{"all flags + sqlc content", generatorIncludes{
			SQLC: true, Templ: true, Protobuf: true, Mockgen: true, Stringer: true,
		}, sqlcContent, true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := tt.includes.allowsContent(tt.content); got != tt.expected {
				t.Errorf("allowsContent() = %v, want %v", got, tt.expected)
			}
		})
	}
}

func TestShouldIncludeFile_WithGenericOverride(t *testing.T) {
	dir := t.TempDir()

	sqlcCode := `// Code generated by sqlc. DO NOT EDIT.
package db

type Query struct {
	Name string
}

func (q *Query) Execute() error {
	return nil
}`

	sqlcPath := filepath.Join(dir, "sqlc1.go")
	if err := os.WriteFile(sqlcPath, []byte(sqlcCode), 0o644); err != nil {
		t.Fatal(err)
	}

	regularCode := "package main\nfunc main() {}\n"

	regularPath := filepath.Join(dir, "regular.go")
	if err := os.WriteFile(regularPath, []byte(regularCode), 0o644); err != nil {
		t.Fatal(err)
	}

	// Build a filter that has FilterGeneric enabled (default for setupFilter with no includes).
	cfg, err := gogenfilter.WithFilterOptions(
		gogenfilter.FilterTempl,
		gogenfilter.FilterProtobuf,
		gogenfilter.FilterMockgen,
		gogenfilter.FilterStringer,
		gogenfilter.FilterGeneric,
	)
	if err != nil {
		t.Fatal(err)
	}

	f, err := gogenfilter.NewFilter(cfg)
	if err != nil {
		t.Fatal(err)
	}

	tests := []struct {
		name     string
		path     string
		includes generatorIncludes
		expected bool
	}{
		{"sqlc file without include flag", sqlcPath, generatorIncludes{}, false},
		{"sqlc file with include-sqlc flag", sqlcPath, generatorIncludes{SQLC: true}, true},
		{"sqlc file with wrong include flag", sqlcPath, generatorIncludes{Templ: true}, false},
		{"regular file without includes", regularPath, generatorIncludes{}, true},
		{"regular file with includes", regularPath, generatorIncludes{SQLC: true}, true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := shouldIncludeFile(f, tt.path, nil, tt.includes)
			if got != tt.expected {
				t.Errorf("shouldIncludeFile() = %v, want %v", got, tt.expected)
			}
		})
	}
}

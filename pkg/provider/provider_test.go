func TestDetect_MultiModuleWorkspaceShape(t *testing.T) {
	dir := t.TempDir()

	write := func(rel, content string) {
		t.Helper()

		path := filepath.Join(dir, filepath.FromSlash(rel))

		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}

		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	// Three modules plus workspace scaffolding.
	for _, mod := range []string{"mod-a", "mod-b", "mod-c"} {
		write(mod+"/go.mod", "module example.com/"+mod+"\n\ngo 1.27\n")
	}

	// Cross-module clone pair: identical 6-statement bodies in mod-a and
	// mod-b (function names differ — package-level API surface).

	cloneBody := "package %s\n\nfunc Process%s(items []int) int {\n\ttotal := 0\n\tscaled := 0\n\toffset := 100\n\tflag := false\n\tfor _, item := range items {\n\t\ttotal += item\n\t\tscaled += item * 2\n\t}\n\tif total > offset {\n\t\tflag = true\n\t}\n\treturn total\n}\n"

	write("mod-a/clone.go", fmt.Sprintf(cloneBody, "a", "A"))
	write("mod-b/clone.go", fmt.Sprintf(cloneBody, "b", "B"))
	// mod-c: a templ file (parsed structurally) and a unique Go file.
	write("mod-c/page.templ", "package c\n\ntempl page() {\n\t<div>unique</div>\n}\n")
	write("mod-c/unique.go", "package c\n\nfunc UniqueC() int { return 7 }\n")

	// Noise that must NOT reach detection: vendor copy of the clone,
	// generated file, dot-dir file.
	write("mod-a/vendor/example.com/mod-b/clone.go", fmt.Sprintf(cloneBody, "b", "B"))
	write("mod-b/gen.go", "// Code generated by sqlc. DO NOT EDIT.\n\npackage b\n")
	write(".hidden/skip.go", "package h\n")

	ctx := toolsdk.EnsureContext(gofinding.WithWorkingDir(context.Background(), dir))

	findings, err := cloneDetector{}.Detect(ctx)
	if err != nil {
		t.Fatalf("detect: %v", err)
	}

	var crossModule bool

	for _, f := range findings {
		if strings.Contains(string(f.Position.File), "mod-a") {
			crossModule = true
		}

		for _, loc := range f.Related {
			if strings.Contains(string(loc.Position.File), "mod-b") {
				crossModule = true
			}
		}

		if strings.Contains(string(f.Position.File), "vendor/") ||
			strings.Contains(string(f.Position.File), ".hidden") ||
			strings.Contains(string(f.Position.File), "gen.go") {
			t.Errorf("finding reaches excluded file: %s", f.Position.File)
		}
	}

	if !crossModule {
		t.Fatalf("cross-module clone not detected; findings: %+v", findings)
	}
}

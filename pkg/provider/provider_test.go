func TestCollectSourceFilesExcludesDefaults(t *testing.T) {
	dir := t.TempDir()

	writeFile(t, dir, "real.go", "package fixtures\n")
	writeFile(t, dir, "real.templ", "package templates\n\ntempl page() {\n\t<div>ok</div>\n}\n")
	writeFile(t, dir, "vendor/lib.go", "package lib\n")
	writeFile(t, dir, "node_modules/pkg.go", "package pkg\n")
	writeFile(t, dir, "examples/demo.go", "package demo\n")
	writeFile(t, dir, ".git/config", "")
	writeFile(t, dir, "generated.go", "// Code generated by sqlc. DO NOT EDIT.\n\npackage db\n")
	writeFile(t, dir, "templ_page_templ.go", "// Code generated by templ. DO NOT EDIT.\n\npackage templates\n")
	writeFile(t, dir, "README.md", "# docs\n")

	files, err := collectSourceFiles(dir)
	if err != nil {
		t.Fatalf("collectSourceFiles: %v", err)
	}

	want := []string{filepath.Join(dir, "real.go"), filepath.Join(dir, "real.templ")}

	if len(files) != len(want) {
		t.Fatalf("collectSourceFiles returned %v, want %v", files, want)
	}

	for i, path := range want {
		if files[i] != path {
			t.Errorf("files[%d] = %q, want %q", i, files[i], path)
		}
	}
}


func TestStripEmptyMetadata_DropsFullClassificationKeySet(t *testing.T) {
	findings := []gofinding.Finding{{
		// A CLI-run finding carries EVERY metadata key; the SDK path
		// zero-values Classification, so after stripEmptyMetadata the
		// classification set must be GONE while interchange keys survive.
		GroupID: "abc",
		Metadata: map[string]string{
			finding.MetadataKeyGroupSize:            "4",
			finding.MetadataKeyGroupTokens:          "16",
			finding.MetadataKeyDetectionMethod:      "semantic",
			finding.MetadataKeyCloneType:            "type-2",
			finding.MetadataKeyCategory:             "block",
			finding.MetadataKeyPriority:             "high",
			finding.MetadataKeyActionability:        "actionable",
			finding.MetadataKeyNonActionablePattern: "",
		},
	}}

	for _, key := range []string{
		finding.MetadataKeyCloneType,
		finding.MetadataKeyCategory,
		finding.MetadataKeyPriority,
		finding.MetadataKeyActionability,
		finding.MetadataKeyNonActionablePattern,
		finding.MetadataKeyGenericsCandidate,
		finding.MetadataKeyGenericsHint,
	} {
		findings[0].Metadata[key] = "" // zero-valued = what the SDK path produces
	}

	stripEmptyMetadata(findings)

	for _, key := range []string{
		finding.MetadataKeyCloneType,
		finding.MetadataKeyCategory,
		finding.MetadataKeyPriority,
		finding.MetadataKeyActionability,
		finding.MetadataKeyNonActionablePattern,
		finding.MetadataKeyGenericsCandidate,
		finding.MetadataKeyGenericsHint,
	} {
		if _, ok := findings[0].Metadata[key]; ok {
			t.Errorf("classification key %q survived stripEmptyMetadata; BuildFlow would render a ghost column", key)
		}
	}

	for _, key := range []string{
		finding.MetadataKeyGroupSize,
		finding.MetadataKeyGroupTokens,
		finding.MetadataKeyDetectionMethod,
	} {
		if findings[0].Metadata[key] == "" {
			t.Errorf("interchange key %q must survive stripEmptyMetadata", key)
		}
	}
}


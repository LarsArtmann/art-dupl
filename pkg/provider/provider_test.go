func TestProviderDetect_ConcurrentSameWorkingDir(t *testing.T) {
	dir := t.TempDir()

	src := "package a\n\nfunc Alpha(items []int) int {\n\ttotal := 0\n\tscaled := 0\n\toffset := 100\n\tflag := false\n\tfor _, item := range items {\n\t\ttotal += item\n\t\tscaled += item * 2\n\t}\n\tif total > offset {\n\t\tflag = true\n\t}\n\treturn total\n}\n"

	for _, name := range []string{"a1.go", "a2.go"} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	const workers = 8

	results := make(chan []gofinding.Finding, workers)
	errs := make(chan error, workers)

	for range workers {
		go func() {
			ctx := gofinding.WithWorkingDir(context.Background(), dir)

			findings, err := cloneDetector{}.Detect(ctx)
			if err != nil {
				errs <- err

				return
			}

			results <- findings
		}()
	}

	var first []gofinding.Finding

	for range workers {
		select {
		case err := <-errs:
			t.Fatalf("concurrent Detect: %v", err)
		case findings := <-results:
			if first == nil {
				first = findings
			} else if len(findings) != len(first) {
				t.Fatalf("racy Detect: got %d findings, want %d", len(findings), len(first))
			}
		case <-time.After(30 * time.Second):
			t.Fatal("timeout waiting for concurrent Detect")
		}
	}

	if len(first) == 0 {
		t.Fatal("fixture clone not detected through Provider.Detect")
	}
}


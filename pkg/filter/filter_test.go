func TestShouldFilter(t *testing.T) {
	t.Run("disabled filter never filters", func(t *testing.T) {
		f := NewFilter(false, []FilterOption{FilterAll})
		assert.False(t, f.ShouldFilter("any/file.go"))
	})

	t.Run("enabled filter with no patterns filters by auto-generated detection", func(t *testing.T) {
		tmpDir := t.TempDir()

		// Create sqlc file
		sqlcFile := filepath.Join(tmpDir, "models.go")
		sqlcContent := `// Code generated by sqlc. DO NOT EDIT.
package db
type User struct {}
`
		assert.NoError(t, os.WriteFile(sqlcFile, []byte(sqlcContent), 0o600)) //nolint:gosec //G306 Test file permissions

		// Create templ file
		templFile := filepath.Join(tmpDir, "header_templ.go")
		templContent := `package components
import "github.com/a-h/templ"
func header() templ.Component { return nil }
`
		assert.NoError(t, os.WriteFile(templFile, []byte(templContent), 0o600)) //nolint:gosec //G306 Test file permissions

		// Create regular file
		regularFile := filepath.Join(tmpDir, "main.go")
		regularContent := `package main
func main() {}
`
		assert.NoError(t, os.WriteFile(regularFile, []byte(regularContent), 0o600)) //nolint:gosec //G306 Test file permissions

		f := NewFilter(true, []FilterOption{FilterAll})
		assert.True(t, f.ShouldFilter(sqlcFile), "should filter sqlc file")
		assert.True(t, f.ShouldFilter(templFile), "should filter templ file")
		assert.False(t, f.ShouldFilter(regularFile), "should not filter regular file")
	})
}

func TestMatchPattern(t *testing.T) {
	tests := []struct {
		name     string
		path     string
		pattern  string
		expected bool
	}{
		{
			name:     "exact match",
			path:     "file.go",
			pattern:  "file.go",
			expected: true,
		},
		{
			name:     "wildcard match",
			path:     "test.go",
			pattern:  "*.go",
			expected: true,
		},
		{
			name:     "wildcard no match",
			path:     "test.txt",
			pattern:  "*.go",
			expected: false,
		},
		{
			name:     "directory pattern",
			path:     "vendor/file.go",
			pattern:  "vendor/*",
			expected: true,
		},
		{
			name:     "complex pattern",
			path:     "generated/sqlc/models.go",
			pattern:  "generated/sqlc/*.go",
			expected: true,
		},
		{
			name:     "filename matches pattern in any directory",
			path:     "src/file.go",
			pattern:  "file.go",
			expected: true, // Pattern without path separator matches filename only
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := matchPattern(tt.path, tt.pattern)
			assert.Equal(t, tt.expected, result)
		})
	}
}

func TestIsSQLCGenerated(t *testing.T) { //nolint:funlen
	tests := []struct {
		name     string
		filePath string
		content  string
		expected bool
	}{
		{
			name:     "sqlc models with comment",
			filePath: "db/models.go",
			content: `// Code generated by sqlc. DO NOT EDIT.
// versions:
//   sqlc v1.30.0
// source: schema.sql

package db

type User struct {
	ID int
}
`,
			expected: true,
		},
		{
			name:     "sqlc query with version comment",
			filePath: "db/query.sql.go",
			content: `package db

// versions:
//   sqlc v1.25.0

const getAuthors = ` + "`-- name: GetAuthors :many\nSELECT * FROM authors`" + `
`,
			expected: true,
		},
		{
			name:     "sqlc with sqlc.Arg",
			filePath: "db/querier.go",
			content: `package db

func (q *Queries) GetAuthor(ctx context.Context, id int64) (Author, error) {
	row := q.db.QueryRowContext(ctx, getAuthor, sqlc.Narg("id"))
	var i Author
	err := row.Scan(&i.ID)
	return i, err
}
`,
			expected: true,
		},
		{
			name:     "not sqlc - regular Go file",
			filePath: "models/user.go",
			content: `package models

type User struct {
	ID string
}
`,
			expected: false,
		},
		{
			name:     "sqlc batch.go",
			filePath: "db/batch.go",
			content: `// Code generated by sqlc. DO NOT EDIT.
package db

type Batch struct {
	// batch implementation
}
`,
			expected: true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := isSQLCGenerated(tt.filePath, tt.content)
			assert.Equal(t, tt.expected, result)
		})
	}
}


func TestShouldFilterIntegration(t *testing.T) { //nolint:funlen
	// Create temporary directory structure
	tmpDir := t.TempDir()

	t.Run("filters sqlc file", func(t *testing.T) {
		sqlcFile := filepath.Join(tmpDir, "models.go")
		content := `// Code generated by sqlc. DO NOT EDIT.
package db
type User struct {}
`
		assert.NoError(t, os.WriteFile(sqlcFile, []byte(content), 0o600)) //nolint:gosec //G306 Test file permissions

		f := NewFilter(true, []FilterOption{FilterSQLC})
		assert.True(t, f.ShouldFilter(sqlcFile))
	})

	t.Run("filters templ file", func(t *testing.T) {
		templFile := filepath.Join(tmpDir, "header_templ.go")
		content := `package components
import "github.com/a-h/templ"
func header() templ.Component { return nil }
`
		assert.NoError(t, os.WriteFile(templFile, []byte(content), 0o644))

		f := NewFilter(true, []FilterOption{FilterTempl})
		assert.True(t, f.ShouldFilter(templFile))
	})

	t.Run("does not filter regular file", func(t *testing.T) {
		regularFile := filepath.Join(tmpDir, "main.go")
		content := `package main
func main() {}
`
		assert.NoError(t, os.WriteFile(regularFile, []byte(content), 0o644))

		f := NewFilter(true, []FilterOption{FilterAll})
		assert.False(t, f.ShouldFilter(regularFile))
	})

	t.Run("include pattern takes precedence", func(t *testing.T) {
		sqlcFile := filepath.Join(tmpDir, "vendor", "models.go")
		content := `// Code generated by sqlc. DO NOT EDIT.
package db
type User struct {}
`
		assert.NoError(t, os.MkdirAll(filepath.Dir(sqlcFile), 0o755))
		assert.NoError(t, os.WriteFile(sqlcFile, []byte(content), 0o644))

		f := NewFilter(true, []FilterOption{FilterAll})
		f.WithIncludePatterns([]string{"vendor/*"})
		assert.False(t, f.ShouldFilter(sqlcFile)) // Should not filter due to include pattern
	})

	t.Run("exclude pattern filters", func(t *testing.T) {
		testFile := filepath.Join(tmpDir, "test.go")
		content := `package test
func TestSomething() {}
`
		assert.NoError(t, os.WriteFile(testFile, []byte(content), 0o644))

		f := NewFilter(true, []FilterOption{})
		f.WithExcludePatterns([]string{"test*.go"})
		assert.True(t, f.ShouldFilter(testFile))
	})
}

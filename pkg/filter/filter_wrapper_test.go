func TestFilterStatsWrapper(t *testing.T) {
	t.Parallel()

	f := NewFilter(true, []FilterOption{FilterAll})
	_ = f.ShouldFilter("db/models.go")
	_ = f.ShouldFilter("main.go")

	stats := f.GetStats()
	if stats.TotalFilesChecked != 2 {
		t.Errorf("Expected 2 checked, got %d", stats.TotalFilesChecked)
	}

	if stats.TotalFiltered() < 1 {
		t.Errorf("Expected at least 1 filtered, got %d", stats.TotalFiltered())
	}
}

func TestMatchPatternWrapper(t *testing.T) {
	t.Parallel()

	tests := []struct {
		path, pattern string
		want          bool
	}{
		{"file.go", "*.go", true},
		{"test.txt", "*.go", false},
		{"vendor/file.go", "vendor/*", true},
	}

	for _, tt := range tests {
		got := gogenfilter.MatchPattern(tt.path, tt.pattern)
		if got != tt.want {
			t.Errorf("MatchPattern(%q, %q) = %v, want %v", tt.path, tt.pattern, got, tt.want)
		}
	}
}

func TestDetectionFunctionsWrapper(t *testing.T) {
	t.Parallel()

	if !gogenfilter.IsSQLCGenerated(
		"db/models.go",
		"// Code generated by sqlc. DO NOT EDIT.\npackage db",
	) {
		t.Error("IsSQLCGenerated should detect sqlc file")
	}

	if !gogenfilter.IsTemplGenerated(
		"page_templ.go",
		"package p\nimport \"github.com/a-h/templ\"\nfunc Page() templ.Component { return nil }",
	) {
		t.Error("IsTemplGenerated should detect templ file")
	}

	if !gogenfilter.IsGoEnumGenerated(
		"status_enum.go",
		"// Code generated by go-enum DO NOT EDIT.\npackage p",
	) {
		t.Error("IsGoEnumGenerated should detect go-enum file")
	}
}

